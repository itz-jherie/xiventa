/** Flyer art exported from the Figma file (public/images/figma/<image hash>.jpg). */
export const img = (hash: string) => `/images/figma/${hash}.jpg`;

type EventSeed = Omit<
  XiventaEvent,
  "id" | "city" | "displayPrice" | "isFree" | "priceLabel" | "description" | "venueLabel"
> & {
  priceLabel?: XiventaEvent["priceLabel"];
  description?: string;
  venueLabel?: string;
};

function ev(seed: EventSeed): XiventaEvent {
  const isFree = seed.priceValue === 0;
  return {
    id: `evt-${seed.slug}`,
    city: "Lagos",
    displayPrice: isFree ? "Free" : `₦${seed.priceValue.toLocaleString("en-NG")}`,
    isFree,
    priceLabel: seed.priceLabel ?? null,
    description: seed.description ?? "",
    venueLabel: seed.venueLabel ?? (seed.venueName === "Online" ? "Online" : `${seed.venueName}, ${seed.neighborhood}`),
    ...seed,
  };
}

